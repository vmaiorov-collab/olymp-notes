// Телефоны (яйца): K телефонов, N этажей. Минимальное число бросков в худшем случае, чтобы найти первый «разбивающий» этаж. O(K·N²).
int eggsSlow(int K, int N) {
    vector<vector<int>> f(K + 1, vector<int>(N + 1, 0));       // f[k][n]: k телефонов, n этажей (неизвестен порог среди n этажей)
    for (int n = 1; n <= N; n++) f[0][n] = INT_MAX / 2;         // без телефонов этажи не различить
    for (int k = 1; k <= K; k++)
        for (int n = 1; n <= N; n++) {
            f[k][n] = INT_MAX;
            for (int x = 1; x <= n; x++)                        // бросаем с x-го этажа: разбился → x−1 этажей, k−1 телефонов; цел → n−x этажей, k телефонов
                f[k][n] = min(f[k][n], 1 + max(f[k - 1][x - 1], f[k][n - x]));
        }
    return f[K][N];
}
// Перевёрнутая динамика (меняем параметр и значение местами): g[t][k] — сколько этажей можно разобрать за t бросков с k телефонами.
// Бросок: разбился → g[t−1][k−1] этажей ниже, цел → g[t−1][k] этажей выше, плюс сам этаж:  g[t][k] = g[t−1][k−1] + g[t−1][k] + 1.
int eggsFast(int K, int N) {
    vector<long long> g(K + 1, 0);
    int t = 0;
    while (g[K] < N) {
        t++;
        for (int k = K; k >= 1; k--) g[k] = g[k - 1] + g[k] + 1;     // k по убыванию — используем значения предыдущего слоя
    }
    return t;
}
