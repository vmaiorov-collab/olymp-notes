// За одну операцию можно вырезать палиндром-подстроку (оставшиеся части склеиваются). Минимум операций, чтобы стереть строку. O(n³).
// f[l][r] — для s[l..r). Первая буква s[l] стирается: сама по себе; вместе с соседней (если равны); или вместе с s[k] (s[k] == s[l]), тогда внутренность s[l+1..k) стирается раньше,
// а её последний палиндром достраивается краями s[l] и s[k] (операций не прибавляется).
int minPalRemovals(const string &s) {
    int n = s.size();
    vector<vector<int>> f(n + 2, vector<int>(n + 2, 0));
    for (int len = 1; len <= n; len++)
        for (int l = 0; l + len <= n; l++) {
            int r = l + len;
            if (len == 1) { f[l][r] = 1; continue; }
            int best = 1 + f[l + 1][r];                         // s[l] стираем отдельно
            if (s[l] == s[l + 1]) best = min(best, 1 + f[l + 2][r]);    // s[l] и s[l+1] — вместе, в одном палиндроме
            for (int k = l + 2; k < r; k++)
                if (s[k] == s[l]) best = min(best, f[l + 1][k] + f[k + 1][r]);   // s[l] и s[k] — края одного палиндрома
            f[l][r] = best;
        }
    return f[0][n];
}
